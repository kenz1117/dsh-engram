/** kind 数据值 → 词典键（面板与走廊图共用一份，避免两处各自硬编码房间名）。 */
export const KIND_KEY: Readonly<Record<string, EngramKey>> = {
  fact: 'kindFact',
  preference: 'kindPreference',
  decision: 'kindDecision',
  episode: 'kindEpisode',
  skill: 'kindSkill',
}

/**
 * Имя комнаты для показа: «fact-3» → «Зал фактов-3».
 * В данных лежит идентификатор (host-половина пишет его же, см. src/i18n/rooms.ts),
 * поэтому перевод делается здесь, средствами словаря хоста. Неизвестный
 * идентификатор возвращается как есть — показать его лучше, чем пустую подпись.
 */
export function roomLabel(roomId: string, t: (key: EngramKey) => string): string {
  const match = /^(.*?)-(\d+)$/.exec(roomId)
  const base = match === null ? roomId : (match[1] ?? roomId)
  const suffix = match === null ? '' : `-${match[2]}`
  const key = KIND_KEY[base]
  return key === undefined ? roomId : `${t(key)}${suffix}`
}

