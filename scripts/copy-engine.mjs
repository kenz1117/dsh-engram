#!/usr/bin/env node
/**
 * 引擎出树（0.13.11）：把嵌入引擎从安装树（optionalDependencies，原生件解包约
 * 300MB，弱网机器 pnpm store 永远填不满，市场更新被限时杀掉，issue #50/#54）
 * 搬进随包分发的 lib/engine/——纯 WASM 技术路线，包里不再有任何原生依赖。
 *
 * 四个文件，全部来自 devDependencies（只在构建机存在，用户安装树里没有）：
 *   1. @huggingface/transformers/dist/transformers.web.js
 *      transformers.js 的 web 构建（ESM，~1MB）。Node 下它的 ONNX 后端是空壳
 *      （node:fs 被构建 stub 掉），必须靠 2 预注入的 ORT 才能推理。
 *   2. onnxruntime-web/dist/ort.bundle.min.mjs
 *      自含 wasm 后端的 ORT 构建（~400KB）。spike 实测必须从绝对路径 import
 *      （不能用包名：exports map 会解析到 onnxruntime-node 原生构建），
 *      经 globalThis[Symbol.for('onnxruntime')] 预注入给 1 用。
 *   3. onnxruntime-web/dist/ort-wasm-simd-threaded.jsep.wasm
 *      wasm 二进制（~28MB），readFileSync 注入 ORT.env.wasm.wasmBinary，
 *      不走网络加载。
 *   4. onnxruntime-web/dist/ort-wasm-simd-threaded.jsep.mjs
 *      emscripten 工厂（~47KB），pathToFileURL 动态 import。
 * 版本钉死关系：onnxruntime-web 必须与 transformers 4.3.2 内部钉死的
 * 1.31.0-dev.20260914-8d85527a0 完全一致，否则工厂与 wasm 二进制不配套。
 *
 * 幂等：每次先删旧 lib/engine/ 再整体拷贝。路径全部经 node:path / node:url
 * 拼装（Windows 开发机也要能跑）。devDependencies 缺失（如 GitHub 源码安装
 * 现场构建但依赖不全）时报错退出——发布一个没有引擎的包比安装失败更糟。
 *
 * 另生成一个解析 shim（lib/engine/node_modules/onnxruntime-web/）：transformers
 * 的 web 构建顶部有 `import * as ONNX_WEB from "onnxruntime-web/webgpu"`——
 * 包名Specifier 必须可解析，模块才能被 import；注入模式下 ONNX_WEB 不会被
 * 消费（globalThis[Symbol.for('onnxruntime')] 优先），但解析这关绕不过。
 * shim 把该 Specifier 指回本目录的 ort.bundle.min.mjs（同一次 ESM 求值，
 * 零额外体积）。
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const engineDir = join(repoRoot, 'lib', 'engine')

/** 源文件（包内路径）→ 落地文件名。顺序即上文的 1→4。 */
const ENGINE_FILES = [
  ['@huggingface/transformers/dist/transformers.web.js', 'transformers.web.js'],
  ['onnxruntime-web/dist/ort.bundle.min.mjs', 'ort.bundle.min.mjs'],
  ['onnxruntime-web/dist/ort-wasm-simd-threaded.jsep.wasm', 'ort-wasm-simd-threaded.jsep.wasm'],
  ['onnxruntime-web/dist/ort-wasm-simd-threaded.jsep.mjs', 'ort-wasm-simd-threaded.jsep.mjs'],
]

const sources = ENGINE_FILES.map(([from, to]) => ({ from: join(repoRoot, 'node_modules', from), to }))

const missing = sources.filter(source => !existsSync(source.from))
if (missing.length > 0) {
  console.error(`[copy-engine] devDependencies 里没有嵌入引擎的源文件（先 pnpm install）:`)
  for (const source of missing) console.error(`  缺 ${source.from}`)
  process.exit(1)
}

rmSync(engineDir, { recursive: true, force: true })
// mkdir 递归建 lib/engine/（lib/ 本身可能还不存在——bundle 前先跑本脚本）。
mkdirSync(engineDir, { recursive: true })

for (const source of sources) {
  const target = join(engineDir, source.to)
  copyFileSync(source.from, target)
  console.log(`[copy-engine] ${basename(source.from)}: ${statSync(target).size.toLocaleString('en-US')} bytes <- ${source.from}`)
}

// —— 解析 shim：包名 Specifier → 本目录的 ORT bundle ——
// transformers web 构建里有真实静态 import："onnxruntime-web/webgpu"（浏览器
// 分支的后端绑定，注入模式下不被消费）与 "onnxruntime-common"（Tensor，运行时
// 真用）。Specifier 必须可解析模块才能 import；两个 shim 都指回本目录的
// ort.bundle.min.mjs——URL 相同，ESM 缓存保证与注入用的是同一个模块实例。
// 版本号取自 devDependencies 里真实的 onnxruntime-web，保持同步不手写。
const ortVersion = JSON.parse(readFileSync(join(repoRoot, 'node_modules', 'onnxruntime-web', 'package.json'), 'utf8')).version
const SHIM_PACKAGES = [
  ['onnxruntime-web', './webgpu.mjs', { '.': './webgpu.mjs', './webgpu': './webgpu.mjs' }],
  ['onnxruntime-common', './index.mjs', { '.': './index.mjs' }],
]
for (const [name, entry, exports] of SHIM_PACKAGES) {
  const shimDir = join(engineDir, 'node_modules', name)
  mkdirSync(shimDir, { recursive: true })
  writeFileSync(
    join(shimDir, 'package.json'),
    JSON.stringify({
      name,
      version: ortVersion,
      description: `Resolution shim generated by scripts/copy-engine.mjs; re-exports the bundled wasm ORT (${ortVersion}).`,
      type: 'module',
      main: entry,
      exports,
    }, null, 2) + '\n',
  )
  writeFileSync(
    join(shimDir, entry.slice(2)),
    `// scripts/copy-engine.mjs 生成的解析 shim：Specifier 必须可解析（transformers\n`
    + `// web 构建的静态 import）；指回同一份 ORT bundle（同 URL = 同一模块实例）。\n`
    + `export * from "../../ort.bundle.min.mjs";\n`,
  )
  console.log(`[copy-engine] resolution shim ${name}@${ortVersion} -> ${shimDir}`)
}
console.log(`[copy-engine] ok: ${sources.length} files + ${SHIM_PACKAGES.length} shims in ${engineDir}`)
