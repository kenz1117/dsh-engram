/**
 * Окно собранного условия смены языка дворца: отсчёт для панели.
 *
 * Проверяется арифметика остатка: панель показывает человеку то же число, которое
 * считает сервер, — иначе человек увидит «ещё 30 секунд» там, где сервер уже отказал.
 *
 * Само условие (открыто ли окно, какой язык, не истекло ли) проверяет сервер — см.
 * tests/palace-guard.spec.ts.
 */
import { describe, expect, it } from 'vitest'
import { windowLeft } from '../src/registry/palace-change.ts'

const NOW = 1_800_000_000_000

describe('отсчёт окна собранного условия', () => {
  it('остаток окна считается и не уходит в минус', () => {
    expect(windowLeft(NOW - 4_000, NOW, 30)).toBe(26)
    expect(windowLeft(NOW - 40_000, NOW, 30)).toBe(0)
    expect(windowLeft(NOW, NOW, 30)).toBe(30)
  })

  it('длина окна берётся из настройки, а не из константы', () => {
    // Пользователь просил менять её без пересборки: «минута это много, 30 сек».
    expect(windowLeft(NOW - 9_000, NOW, 10)).toBe(1)
    expect(windowLeft(NOW - 9_000, NOW, 5)).toBe(0)
  })
})
